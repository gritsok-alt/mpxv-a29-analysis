#!/usr/bin/env python3
"""
Analyse a set of restrained Boltz-2 predictions.

  1. classify chain orientation (P / AP / X)
  2. relabel chains to a common convention:
        A = the restrained partner of the antiparallel chain
        C = the antiparallel chain
        B = the remaining chain (unrestrained relative to C)
  3. check each imposed restraint
  4. determine which heptad face (e or g) each parallel chain presents to C
  5. write per-model and per-seed tables
  6. compute the ensemble spread (per-residue RMSF) over accepted models
  7. select the reported model

Usage:
    python analyse_models.py <results_dir> [--out <out_dir>]

<results_dir> is the folder holding results_<target>_<tag>_seed*/ subfolders.
"""

import argparse
import itertools
import json
import sys
from pathlib import Path

import numpy as np

try:
    import gemmi
except ImportError:
    sys.exit("gemmi is required:  pip install gemmi")


# ---------------------------------------------------------------- configuration

# Restraints as imposed, in native numbering: (chain, res, chain, res)
RESTRAINTS = [("A", 47, "C", 65), ("A", 65, "C", 47)]
MAX_DISTANCE = 8.0

FIRST_RESIDUE = 1            # 21 for the 3VOP construct
CC_START, CC_END = 44, 100   # helix-axis fit and heptad-face assignment

# Segment the ensemble is superposed on before RMSF is measured.
# Overridable with --fit; kept separate from CC_START/CC_END so that changing
# it alters ONLY the superposition, not the topology or face assignment.
FIT_START, FIT_END = 44, 100

REGIONS = [("N-terminal coil", 1, 28), ("short helix", 29, 39), ("coil linker", 40, 43),
           ("coiled_coil", 44, 100), ("C-terminal region", 101, 110), ("global", 1, 110)]

# Heptad positions from the sequence-based assignment (native numbering)
HEPTAD_E = {48, 55, 62}
HEPTAD_G = {50, 57, 64}

# Acceptance criteria for inclusion in the ensemble and for model selection
MIN_IPTM = 0.60
REQUIRE_AP = True
REQUIRE_RESTRAINTS_SATISFIED = False   # marginal violations are reported, not excluded



