# ---------------------------------------------------------------- geometry helpers

def load(path):
    st = gemmi.read_structure(str(path))
    st.setup_entities()
    st.remove_alternative_conformations()
    return st


def ca_coords(chain, lo, hi):
    pts, nums = [], []
    for r in chain:
        n = r.seqid.num + FIRST_RESIDUE - 1
        if lo <= n <= hi:
            a = r.find_atom("CA", "*")
            if a:
                pts.append([a.pos.x, a.pos.y, a.pos.z])
                nums.append(n)
    return np.array(pts), nums


def helix_axis(chain):
    """Least-squares axis through the coiled-coil CA atoms, oriented N->C."""
    P, _ = ca_coords(chain, CC_START, CC_END)
    if len(P) < 8:
        return None
    v = np.linalg.svd(P - P.mean(axis=0), full_matrices=False)[2][0]
    if np.dot(P[-1] - P[0], v) < 0:
        v = -v
    return v / np.linalg.norm(v)


def classify(axes):
    dots = {f"{a}-{b}": float(np.dot(axes[a], axes[b]))
            for a, b in itertools.combinations(sorted(axes), 2)}
    v = list(dots.values())
    if all(x > 0.7 for x in v):
        cls = "P"
    elif sum(x > 0.7 for x in v) == 1 and sum(x < -0.7 for x in v) == 2:
        cls = "AP"
    else:
        cls = "X"
    return cls, dots


def atom_pos(st, ch, num, name="CB"):
    """Position of an atom, by NATIVE residue number."""
    target = num - (FIRST_RESIDUE - 1)
    try:
        chain = st[0][ch]
    except Exception:
        return None
    for r in chain:
        if r.seqid.num == target:
            a = r.find_atom(name, "*") or r.find_atom("CA", "*")
            return a.pos if a else None
    return None


# ---------------------------------------------------------------- relabelling

def relabel_map(st, axes):
    """
    Return {current_chain: new_label} for an antiparallel model.

    C  = the antiparallel chain (the one whose axis opposes the other two)
    A  = the chain whose restraints to C are satisfied (the restrained partner)
    B  = the remaining chain
    """
    names = sorted(axes)
    # the antiparallel chain is the one with a negative dot product to both others
    anti = [n for n in names
            if all(np.dot(axes[n], axes[m]) < 0 for m in names if m != n)]
    if len(anti) != 1:
        return None
    c_chain = anti[0]
    others = [n for n in names if n != c_chain]

    # which of the two satisfies the imposed restraints to the antiparallel chain?
    best, best_score = None, None
    for cand in others:
        total = 0.0
        ok = True
        for ch1, r1, ch2, r2 in RESTRAINTS:
            # restraints were imposed as (A,r1)-(C,r2); test cand in the A role
            p1 = atom_pos_chain(st, cand, r1)
            p2 = atom_pos_chain(st, c_chain, r2)
            if p1 is None or p2 is None:
                ok = False
                break
            total += p1.dist(p2)
        if ok and (best_score is None or total < best_score):
            best, best_score = cand, total

    if best is None:
        best = others[0]
    a_chain = best
    b_chain = [n for n in others if n != a_chain][0]
    return {a_chain: "A", b_chain: "B", c_chain: "C"}


def atom_pos_chain(st, ch, num, name="CB"):
    target = num - (FIRST_RESIDUE - 1)
    for r in st[0][ch]:
        if r.seqid.num == target:
            a = r.find_atom(name, "*") or r.find_atom("CA", "*")
            return a.pos if a else None
    return None


def apply_labels(st, mapping):
    tmp = {old: f"__{new}" for old, new in mapping.items()}
    for ch in st[0]:
        if ch.name in tmp:
            ch.name = tmp[ch.name]
    for ch in st[0]:
        if ch.name.startswith("__"):
            ch.name = ch.name[2:]
    return st


# ---------------------------------------------------------------- face assignment

def cb_atoms(chain, lo, hi):
    """CB coordinates (CA for glycine) with native residue numbers."""
    pts, nums = [], []
    for r in chain:
        n = r.seqid.num + FIRST_RESIDUE - 1
        if lo <= n <= hi:
            a = r.find_atom("CB", "*") or r.find_atom("CA", "*")
            if a:
                pts.append([a.pos.x, a.pos.y, a.pos.z])
                nums.append(n)
    return np.array(pts), nums


def interface_face(st, parallel_chain, anti_chain, cutoff=8.0):
    """
    Which heptad face does `parallel_chain` present to `anti_chain`?

    Uses the same criterion as the crystal analysis: CB-CB pairs within
    `cutoff` (CA substituted for glycine). Counts how many distinct e and
    g positions of the parallel chain make contact.
    """
    P, pn = cb_atoms(st[0][parallel_chain], CC_START, CC_END)
    Q, _ = cb_atoms(st[0][anti_chain], CC_START, CC_END)
    if len(P) == 0 or len(Q) == 0:
        return "?", 0, 0
    d = np.linalg.norm(P[:, None, :] - Q[None, :, :], axis=2)
    close = {pn[i] for i in np.where((d <= cutoff).any(axis=1))[0]}
    e = len(close & HEPTAD_E)
    g = len(close & HEPTAD_G)
    face = "g" if g > e else "e" if e > g else ("=" if (e or g) else "-")
    return face, e, g


# ---------------------------------------------------------------- per-model pass

def analyse_model(cif, conf_json, seed):
    st = load(cif)
    axes = {ch.name: helix_axis(ch) for ch in st[0]}
    axes = {k: v for k, v in axes.items() if v is not None}
    if len(axes) < 3:
        return None

    cls, dots = classify(axes)

    mapping = relabel_map(st, axes) if cls == "AP" else None
    if mapping:
        st = apply_labels(st, mapping)

    # restraint check, in the relabelled frame where possible
    viol, dists = [], {}
    for ch1, r1, ch2, r2 in RESTRAINTS:
        p1, p2 = atom_pos_chain(st, ch1, r1), atom_pos_chain(st, ch2, r2)
        if p1 and p2:
            d = p1.dist(p2)
            dists[f"{ch1}{r1}-{ch2}{r2}"] = round(d, 2)
            if d > MAX_DISTANCE:
                viol.append(f"{ch1}{r1}-{ch2}{r2}={d:.1f}")

    # regional pLDDT
    b = {}
    for ch in st[0]:
        for r in ch:
            a = r.find_atom("CA", "*")
            if a:
                b.setdefault(r.seqid.num + FIRST_RESIDUE - 1, []).append(a.b_iso)
    regional = {}
    for lbl, lo, hi in REGIONS:
        vals = [x for k, v in b.items() if lo <= k <= hi for x in v]
        regional[lbl] = round(float(np.mean(vals)), 1) if vals else None

    # interface faces
    if mapping:
        fa, ea, ga = interface_face(st, "A", "C")
        fb, eb, gb = interface_face(st, "B", "C")
    else:
        fa = fb = "-"
        ea = ga = eb = gb = 0

    conf = json.loads(Path(conf_json).read_text()) if Path(conf_json).exists() else {}

    dist_flat = {f"d_{k.replace('-', '_')}": v for k, v in dists.items()}

    return {
        **dist_flat,
        "seed": seed,
        "model": cif.stem.split("_model_")[-1],
        "file": str(cif),
        "class": cls,
        "dots": {k: round(v, 2) for k, v in dots.items()},
        "confidence": round(conf.get("confidence_score", float("nan")), 3),
        "ptm": round(conf.get("ptm", float("nan")), 3),
        "iptm": round(conf.get("iptm", float("nan")), 3),
        "restraint_dist": dists,
        "max_restraint_dist": (round(max(dists.values()), 2) if dists else None),
        "restraints_ok": not viol,
        "violations": "; ".join(viol),
        "face_A_to_C": fa,
        "face_B_to_C": fb,
        "A_to_C_e": ea, "A_to_C_g": ga,
        "B_to_C_e": eb, "B_to_C_g": gb,
        "relabelled": bool(mapping),
        "structure": st,
        **{f"plddt_{lbl.replace(' ', '_').replace('-', '_')}": v
           for lbl, v in regional.items()},
    }


# ---------------------------------------------------------------- ensemble spread

def superpose_stack(rows, lo, hi):
    """
    Superpose accepted models over the CC segment and return coordinates
    for residues lo-hi of every chain, stacked over models.
    Returns (labels, array[n_models, n_atoms, 3]) or (None, None).
    """
    fit_ref = None
    labels = None
    stack = []

    for r in rows:
        st = r["structure"]
        fit, full, lab = [], [], []
        ok = True
        for ch_name in ("A", "B", "C"):
            try:
                ch = st[0][ch_name]
            except Exception:
                ok = False
                break
            F, _ = ca_coords(ch, FIT_START, FIT_END)  # fitting atoms
            P, n = ca_coords(ch, lo, hi)               # reported atoms
            fit.append(F)
            full.append(P)
            lab += [f"{ch_name}:{x}" for x in n]
        if not ok:
            continue
        F = np.vstack(fit)
        X = np.vstack(full)
        if fit_ref is None:
            fit_ref, labels, ref_n = F, lab, X.shape[0]
        if F.shape != fit_ref.shape or X.shape[0] != ref_n:
            continue

        fc = F.mean(0)
        Fc, Rc = F - fc, fit_ref - fit_ref.mean(0)
        U, _, Vt = np.linalg.svd(Fc.T @ Rc)
        d = np.sign(np.linalg.det(U @ Vt))
        R = U @ np.diag([1, 1, d]) @ Vt
        stack.append((X - fc) @ R)

    if not stack:
        return None, None
    return labels, np.stack(stack)


def per_residue_table(rows, lo, hi):
    """Per-position RMSF and pLDDT statistics across the accepted models."""
    labels, A = superpose_stack(rows, lo, hi)
    if A is None:
        return None

    mean = A.mean(0)
    rmsf = np.sqrt(((A - mean) ** 2).sum(-1).mean(0))

    # per-position pLDDT across models
    plddt = {}
    for r in rows:
        st = r["structure"]
        for ch_name in ("A", "B", "C"):
            try:
                ch = st[0][ch_name]
            except Exception:
                continue
            for res in ch:
                n = res.seqid.num + FIRST_RESIDUE - 1
                if lo <= n <= hi:
                    a = res.find_atom("CA", "*")
                    if a:
                        plddt.setdefault(f"{ch_name}:{n}", []).append(a.b_iso)

    out = []
    for lab, v in zip(labels, rmsf):
        ch, num = lab.split(":")
        p = plddt.get(lab, [])
        out.append({
            "chain": ch,
            "residue": int(num),
            "rmsf": round(float(v), 2),
            "plddt_mean": round(float(np.mean(p)), 1) if p else None,
            "plddt_sd": round(float(np.std(p)), 1) if p else None,
            "plddt_min": round(float(np.min(p)), 1) if p else None,
            "plddt_max": round(float(np.max(p)), 1) if p else None,
            "n_models": len(p),
        })
    return out


# ---------------------------------------------------------------- main

def main():
    global FIT_START, FIT_END
    ap = argparse.ArgumentParser()
    ap.add_argument("results_dir",
                    help="folder containing results_*_seed*/ subfolders")
    ap.add_argument("--out", default=None,
                    help="output folder (default: <results_dir>/analysis_output)")
    ap.add_argument("--fit", nargs=2, type=int, metavar=("LO", "HI"),
                    default=(44, 100),
                    help=f"residue range the ensemble is superposed on before "
                         f"RMSF is measured (default {FIT_START} {FIT_END}). "
                         f"Use --fit 47 65 to repeat the analysis on the "
                         f"trimeric core as a sensitivity check.")
    args = ap.parse_args()
    FIT_START, FIT_END = args.fit

    root = Path(args.results_dir).expanduser().resolve()
    if not root.is_dir():
        sys.exit(f"Not a directory: {root}")
    out = Path(args.out).expanduser().resolve() if args.out else root / "analysis_output"
    print(f"Reading : {root}")
    print(f"Writing : {out}")
    print(f"Fit on  : residues {FIT_START}-{FIT_END} "
          f"(CA, all three chains){'  [default]' if (FIT_START, FIT_END) == (44, 100) else '  [sensitivity check]'}\n")
    (out / "relabelled").mkdir(parents=True, exist_ok=True)

    cifs = sorted(root.glob("results_*_seed*/**/*model_*.cif"))
    if not cifs:
        sys.exit(f"No model files found under {root}")

    rows = []
    for cif in cifs:
        seed = None
        for p in cif.parts:
            if "_seed" in p:
                seed = int(p.split("_seed")[-1])
        conf = cif.parent / ("confidence_" + cif.name.replace(".cif", ".json"))
        r = analyse_model(cif, conf, seed)
        if r:
            rows.append(r)

    rows.sort(key=lambda r: (r["seed"], r["model"]))

    # write relabelled structures
    for r in rows:
        if r["relabelled"]:
            p = out / "relabelled" / f"seed{r['seed']:02d}_model{r['model']}.cif"
            r["structure"].setup_entities()
            doc = r["structure"].make_mmcif_document()
            doc.write_file(str(p))

    # ---- per-model table
    dist_cols = [f"d_{c1}{r1}_{c2}{r2}" for c1, r1, c2, r2 in RESTRAINTS]
    cols = (["seed", "model", "class", "confidence", "ptm", "iptm",
             "plddt_N_terminal", "plddt_spacer", "plddt_coiled_coil",
             "plddt_C_terminal"]
            + dist_cols
            + ["max_restraint_dist", "restraints_ok", "violations",
               "face_A_to_C", "A_to_C_e", "A_to_C_g",
               "face_B_to_C", "B_to_C_e", "B_to_C_g"])

    with open(out / "per_model.tsv", "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows:
            fh.write("\t".join(str(r.get(c, "")) for c in cols) + "\n")

    # ---- per-seed summary
    seeds = sorted({r["seed"] for r in rows})
    with open(out / "per_seed.tsv", "w") as fh:
        fh.write("seed\tn\tAP\tP\tX\tptm\tiptm\tconfidence\t"
                 "plddt_cc\trestraints_ok\n")
        for s in seeds:
            g = [r for r in rows if r["seed"] == s]
            fh.write(f"{s}\t{len(g)}\t"
                     f"{sum(r['class']=='AP' for r in g)}\t"
                     f"{sum(r['class']=='P' for r in g)}\t"
                     f"{sum(r['class']=='X' for r in g)}\t"
                     f"{np.mean([r['ptm'] for r in g]):.3f}\t"
                     f"{np.mean([r['iptm'] for r in g]):.3f}\t"
                     f"{np.mean([r['confidence'] for r in g]):.3f}\t"
                     f"{np.mean([r['plddt_coiled_coil'] for r in g]):.1f}\t"
                     f"{sum(r['restraints_ok'] for r in g)}\n")

    # ---- acceptance and selection
    accepted = [r for r in rows
                if (not REQUIRE_AP or r["class"] == "AP")
                and r["iptm"] >= MIN_IPTM
                and (not REQUIRE_RESTRAINTS_SATISFIED or r["restraints_ok"])]

    # ---- per-residue ensemble statistics, full sequence
    SEQ_LO, SEQ_HI = FIRST_RESIDUE, FIRST_RESIDUE + 109
    per_res = per_residue_table(accepted, SEQ_LO, SEQ_HI)
    if per_res:
        with open(out / "per_residue.tsv", "w") as fh:
            keys = ["chain", "residue", "rmsf", "plddt_mean", "plddt_sd",
                    "plddt_min", "plddt_max", "n_models"]
            fh.write("\t".join(keys) + "\n")
            for row in per_res:
                fh.write("\t".join(str(row[k]) for k in keys) + "\n")
    rmsf = np.array([r["rmsf"] for r in per_res]) if per_res else None

    # ---- report
    n_ap = sum(r["class"] == "AP" for r in rows)
    n_p = sum(r["class"] == "P" for r in rows)
    n_x = sum(r["class"] == "X" for r in rows)

    print(f"{len(rows)} models from {len(seeds)} seeds "
          f"(seeds {min(seeds)}-{max(seeds)})")
    print(f"  topology      : AP {n_ap}, P {n_p}, X {n_x}")
    print(f"  restraints ok : {sum(r['restraints_ok'] for r in rows)}/{len(rows)}")
    md = [r for r in rows if r["max_restraint_dist"] is not None]
    if md:
        near = [r for r in md if MAX_DISTANCE * 0.9 < r["max_restraint_dist"] <= MAX_DISTANCE]
        over = [r for r in md if r["max_restraint_dist"] > MAX_DISTANCE]
        v = np.array([r["max_restraint_dist"] for r in md])
        print(f"  restraint dist: max per model {v.mean():.2f} ± {v.std():.2f} A "
              f"(range {v.min():.2f}-{v.max():.2f})")
        if near:
            print(f"                  {len(near)} model(s) within 10% of the bound: "
                  + ", ".join(f"seed {r['seed']} s{r['model']} "
                              f"({r['max_restraint_dist']:.1f} A)" for r in near))
        if over:
            print(f"                  {len(over)} model(s) exceeding the bound: "
                  + ", ".join(f"seed {r['seed']} s{r['model']} "
                              f"({r['max_restraint_dist']:.1f} A)" for r in over))
    print(f"  accepted      : {len(accepted)} "
          f"(AP, ipTM >= {MIN_IPTM})")
    print()
    for k in ("ptm", "iptm", "confidence"):
        v = np.array([r[k] for r in accepted])
        print(f"  {k:11s} {v.mean():.3f} ± {v.std():.3f} "
              f"({v.min():.3f}-{v.max():.3f})")
    print()
    for lbl, _, _ in REGIONS:
        key = f"plddt_{lbl.replace(' ', '_').replace('-', '_')}"
        v = np.array([r[key] for r in accepted if r[key] is not None])
        if len(v):
            rng = f"{[x for x in REGIONS if x[0] == lbl][0][1]}-" \
                  f"{[x for x in REGIONS if x[0] == lbl][0][2]}"
            print(f"  pLDDT {lbl:13s} {rng:>8s}  {v.mean():5.1f} ± {v.std():.1f} "
                  f"({v.min():.1f}-{v.max():.1f})")

    faces = {}
    for r in accepted:
        faces[(r["face_A_to_C"], r["face_B_to_C"])] = \
            faces.get((r["face_A_to_C"], r["face_B_to_C"]), 0) + 1
    print(f"\n  interface faces (A->C, B->C): {faces}")
    print("  crystal reference: A->C uses g, B->C uses e")

    if per_res:
        cc = [r for r in per_res if CC_START <= r["residue"] <= CC_END]
        rest = [r for r in per_res if not (CC_START <= r["residue"] <= CC_END)]
        print(f"\n  ensemble RMSF over {len(accepted)} models (full length):")
        print(f"    all positions   mean {rmsf.mean():5.2f} A   max {rmsf.max():5.2f} A")
        if cc:
            v = np.array([r["rmsf"] for r in cc])
            print(f"    coiled coil     mean {v.mean():5.2f} A   max {v.max():5.2f} A")
        if rest:
            v = np.array([r["rmsf"] for r in rest])
            print(f"    outside CC      mean {v.mean():5.2f} A   max {v.max():5.2f} A")
        worst = max(per_res, key=lambda r: r["rmsf"])
        print(f"    most variable   {worst['chain']}{worst['residue']} "
              f"({worst['rmsf']:.2f} A)")

    # ---- best model per metric
    def tag(r):
        return f"seed {r['seed']:2d} sample {r['model']}"

    print("\n  best model by each metric (accepted set):")
    for key, label in (("iptm", "ipTM"), ("ptm", "pTM"),
                       ("confidence", "confidence score"),
                       ("plddt_coiled_coil", "pLDDT coiled coil"),
                       ("plddt_C-terminal", "pLDDT C-terminal"),
                       ("plddt_spacer", "pLDDT spacer"),
                       ("plddt_N-terminal", "pLDDT N-terminal")):
        pool = [r for r in accepted if r.get(key) is not None]
        if not pool:
            continue
        b = max(pool, key=lambda r: r[key])
        w = min(pool, key=lambda r: r[key])
        print(f"    {label:20s} best {b[key]:>6}  ({tag(b)})"
              f"   worst {w[key]:>6}  ({tag(w)})")

    # how often does one model top more than one metric?
    from collections import Counter
    tops = Counter()
    for key in ("iptm", "ptm", "confidence", "plddt_coiled_coil"):
        pool = [r for r in accepted if r.get(key) is not None]
        if pool:
            b = max(pool, key=lambda r: r[key])
            tops[(b["seed"], b["model"])] += 1
    multi = [k for k, v in tops.items() if v > 1]
    if multi:
        print(f"    model(s) topping more than one metric: "
              + ", ".join(f"seed {s} sample {m}" for s, m in multi))

    if accepted:
        best = max(accepted, key=lambda r: r["iptm"])
        alt = max(accepted, key=lambda r: r["confidence"])
        print(f"\n  selected model (highest ipTM): "
              f"seed {best['seed']}, sample {best['model']}")
        print(f"    iptm {best['iptm']}  ptm {best['ptm']}  "
              f"confidence {best['confidence']}")
        print(f"    pLDDT cc {best['plddt_coiled_coil']}  "
              f"restraints {best['restraint_dist']}")
        print(f"    {best['file']}")
        if (alt["seed"], alt["model"]) != (best["seed"], best["model"]):
            print(f"\n  note: the highest composite confidence score is a "
                  f"different model,")
            print(f"    seed {alt['seed']} sample {alt['model']} "
                  f"(confidence {alt['confidence']}, iptm {alt['iptm']}, "
                  f"pLDDT cc {alt['plddt_coiled_coil']}).")
            print(f"    ipTM is used for selection because it scores the "
                  f"assembly rather than")
            print(f"    the individual chains, which is what the restrained "
                  f"model is about.")

    # ---- Excel workbook
    xlsx = out / "analysis.xlsx"
    try:
        import pandas as pd

        df_model = pd.DataFrame([{k: r.get(k) for k in cols} for r in rows])
        df_seed = pd.read_csv(out / "per_seed.tsv", sep="\t")
        df_res = pd.DataFrame(per_res) if per_res else pd.DataFrame()

        summary = []
        summary.append(("Models", len(rows)))
        summary.append(("Superposition range for RMSF", f"{FIT_START}-{FIT_END}"))
        summary.append(("Acceptance criteria",
                        f"antiparallel topology and ipTM ≥ {MIN_IPTM}"))
        summary.append(("Seeds", f"{min(seeds)}-{max(seeds)}"))
        summary.append(("Antiparallel", n_ap))
        summary.append(("Parallel", n_p))
        summary.append(("Other", n_x))
        summary.append(("Restraints satisfied", sum(r["restraints_ok"] for r in rows)))
        summary.append(("Accepted (AP, ipTM >= %.2f)" % MIN_IPTM, len(accepted)))
        for k, lbl in (("ptm", "pTM"), ("iptm", "ipTM"),
                       ("confidence", "Confidence score")):
            v = np.array([r[k] for r in accepted])
            summary.append((lbl, f"{v.mean():.3f} ± {v.std():.3f} "
                                 f"({v.min():.3f}-{v.max():.3f})"))
        for lbl, _, _ in REGIONS:
            key = f"plddt_{lbl.replace(' ', '_').replace('-', '_')}"
            v = np.array([r[key] for r in accepted if r[key] is not None])
            if len(v):
                rr = [x for x in REGIONS if x[0] == lbl][0]
                summary.append((f"pLDDT {lbl} ({rr[1]}-{rr[2]})",
                                f"{v.mean():.1f} ± {v.std():.1f} "
                                f"({v.min():.1f}-{v.max():.1f})"))
        if per_res:
            summary.append(("Ensemble RMSF, mean", f"{rmsf.mean():.2f} A"))
            summary.append(("Ensemble RMSF, max", f"{rmsf.max():.2f} A"))
        if accepted:
            summary.append(("Selected model (highest ipTM)",
                            f"seed {best['seed']} sample {best['model']}"))
            summary.append(("Highest composite confidence",
                            f"seed {alt['seed']} sample {alt['model']}"))
        df_sum = pd.DataFrame(summary, columns=["Metric", "Value"])

        df_gloss = pd.DataFrame(GLOSSARY[1:], columns=list(GLOSSARY[0]))

        with pd.ExcelWriter(xlsx, engine="openpyxl") as xw:
            df_sum.to_excel(xw, sheet_name="Summary", index=False)
            df_gloss.to_excel(xw, sheet_name="Glossary", index=False)
            df_seed.to_excel(xw, sheet_name="Per seed", index=False)
            df_model.to_excel(xw, sheet_name="Per model", index=False)
            if not df_res.empty:
                df_res.to_excel(xw, sheet_name="Per residue", index=False)
            from openpyxl.styles import Alignment
            for ws in xw.book.worksheets:
                ws.freeze_panes = "A2"
                for col in ws.columns:
                    width = max(len(str(c.value or "")) for c in col) + 2
                    ws.column_dimensions[col[0].column_letter].width = min(width, 45)
                if ws.title == "Glossary":
                    ws.column_dimensions["C"].width = 80
                    for row in ws.iter_rows(min_row=2, min_col=3, max_col=3):
                        for c in row:
                            c.alignment = Alignment(wrap_text=True, vertical="top")
        print(f"\n  Excel workbook: {xlsx}")
    except ImportError:
        print("\n  (pandas/openpyxl not installed - skipped Excel export)")
        print("   pip install pandas openpyxl --break-system-packages")

    with open(out / "glossary.txt", "w", encoding="utf-8") as fh:
        fh.write("Column glossary\n" + "=" * 60 + "\n\n")
        cur = None
        for sheet, col, meaning in GLOSSARY[1:]:
            if sheet != cur:
                fh.write(f"\n[{sheet}]\n")
                cur = sheet
            fh.write(f"  {col}\n      {meaning}\n")

    print(f"\nWritten to {out}/")
    print("  per_model.tsv, per_seed.tsv, per_residue.tsv, glossary.txt,")
    print("  analysis.xlsx (Summary / Glossary / Per seed / Per model / Per residue),")
    print("  relabelled/")


if __name__ == "__main__":
    main()
